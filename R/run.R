# Running, extending and resuming studies ----------------------------------

new_manifest <- function(study, seed, replications, label, registry = NULL) {
  list(schema_version = SCHEMA_VERSION, study = strip_sources(study), seed = seed,
       replications = as.integer(replications), label = label,
       created = now_utc(), fingerprints = study_fingerprints(study),
       study_fingerprint = sim_fingerprint(study),
       rng_registry = rng_registry(rng_keys(study), registry),
       revisions = list(), environment = environment_info(study_packages(study)),
       # Pilot and calibration directories draw from their own stream
       # families (fixed at creation), never from the production streams.
       rng_domain = if (isTRUE(label %in% c("pilot", "calibration"))) label else NULL,
       status = "created")
}

study_packages <- function(study) {
  unique(c(study$generator$packages, unlist(lapply(study$methods, `[[`, "packages"))))
}

rng_keys <- function(study, dgp_stage = "dgp", method_stage = "method") {
  keys <- study$scenarios$keys
  comps <- method_stream_components(study)
  rbind(
    data.frame(stage = dgp_stage,
               scenario_key = unique(vapply(keys, data_stream_key, character(1), study = study)),
               component = "data", stringsAsFactors = FALSE),
    expand.grid(stage = method_stage, scenario_key = keys, component = comps,
                stringsAsFactors = FALSE),
    truth_stream_keys(study)
  )
}

# Compare a study with an existing manifest. Returns the updated manifest
# or stops with an explanation.
reconcile_manifest <- function(man, study, seed, replications, update) {
  if (!identical(as.numeric(man$seed), as.numeric(seed))) {
    stopf("This run directory was created with seed %s, not %s. Use a new directory for a different seed.",
          man$seed, seed)
  }
  old <- man$fingerprints
  # A study read back from the manifest (sim_resume() without a new study)
  # keeps its stored fingerprints: recomputing them in another session could
  # differ only because globals or attached packages differ.
  resume <- isTRUE(attr(study, "adempr_stored"))
  new <- if (resume) old else study_fingerprints(study)
  study_fp <- if (resume) man$study_fingerprint else sim_fingerprint(study)
  changes <- character()
  alters <- logical()
  chg <- function(text, alter) {
    changes <<- c(changes, text)
    alters <<- c(alters, rep(alter, length(text)))
  }
  if (!identical(old$generator, new$generator)) {
    stopf("The data-generating mechanism differs from the one used in this run directory. Existing results were generated by another mechanism; use a new run directory.")
  }
  added_scen <- setdiff(names(new$scenarios), names(old$scenarios))
  if (length(added_scen)) chg(sprintf("added %d scenario(s)", length(added_scen)), FALSE)
  if (!identical(old$design, new$design)) {
    chg("scenario design changed (weights, distribution, constraints or exclusions): re-evaluate", TRUE)
  }
  removed_scen <- setdiff(names(old$scenarios), names(new$scenarios))
  if (length(removed_scen)) {
    chg(sprintf(
      "removed %d scenario(s): their committed results stay on disk and are excluded from summaries",
      length(removed_scen)), TRUE)
  }
  removed_m <- setdiff(names(old$methods), names(new$methods))
  if (length(removed_m)) {
    chg(sprintf(
      "removed method %s: its committed results stay on disk and are excluded from summaries",
      removed_m), TRUE)
  }
  changed_m <- character()
  for (mn in names(new$methods)) {
    if (is.null(old$methods[[mn]])) {
      chg(sprintf("added method %s", mn), FALSE)
    } else if (!identical(old$methods[[mn]], new$methods[[mn]])) {
      changed_m <- c(changed_m, mn)
    }
  }
  if (length(changed_m) && isFALSE(update)) {
    stopf("Method(s) %s changed since their results were computed. Rerun with `update = TRUE` to refit them (earlier fits are kept but superseded), or use a new run directory.",
          paste(changed_m, collapse = ", "))
  }
  if (length(changed_m)) chg(sprintf("method %s changed: refit", changed_m), TRUE)
  for (en in union(names(old$truth), names(new$truth))) {
    if (!identical(old$truth[[en]], new$truth[[en]])) {
      chg(sprintf("truth of %s changed: re-evaluate", en), TRUE)
    }
  }
  for (en in union(names(old$estimands), names(new$estimands))) {
    if (!is.null(old$estimands[[en]]) && !is.null(new$estimands[[en]]) &&
        !identical(old$estimands[[en]], new$estimands[[en]])) {
      chg(sprintf("metadata of estimand %s changed: re-evaluate", en), TRUE)
    }
  }
  if (!identical(old$evaluation, new$evaluation)) {
    chg("performance measures or failure policy changed: re-evaluate", TRUE)
  }
  if (!identical(old$execution, new$execution)) {
    what <- character()
    if (!identical(old$execution$retries, new$execution$retries)) what <- "retries"
    for (mn in intersect(names(old$execution$timeout), names(new$execution$timeout))) {
      if (!identical(old$execution$timeout[[mn]], new$execution$timeout[[mn]])) {
        what <- c(what, sprintf("timeout of %s", mn))
      }
    }
    if (length(what)) {
      chg(sprintf(
        "execution settings changed (%s): committed fits keep the old settings; only new work uses the new ones (use `retry_failed = TRUE` to rerun failed fits)",
        paste(what, collapse = ", ")), FALSE)
    }
  }
  if (replications > man$replications) {
    chg(sprintf("replications extended from %d to %d", man$replications,
                as.integer(replications)), FALSE)
  } else if (replications < man$replications && is.null(man$sequential)) {
    # (A sequential run analyzes its look prefix, so no warning there.)
    warnf("This run directory holds %d replications per scenario; %d were requested. All %d are kept and summarized.",
             man$replications, as.integer(replications), man$replications)
  }
  # A production run is the record of the study: changes that supersede or
  # re-evaluate its results need an explicit confirmation. Extensions (more
  # replications, added scenarios or methods) do not.
  # changes to the protocol that leave every stage fingerprint unchanged
  # (aims, protocol fields, name, retention, the freeze record)
  if (!length(changes) && !resume && !identical(man$study_fingerprint, study_fp)) {
    chg("protocol text or settings changed (aims, protocol fields, name or retention)", FALSE)
  }
  old_freeze <- man$study$status$frozen
  if (!resume && !is.null(old_freeze) &&
      !identical(old_freeze$hash, study$status$frozen$hash)) {
    chg("the study's freeze record changed (a study rebuilt or frozen again)", TRUE)
  }
  altering <- changes[alters]
  if (length(altering) && identical(man$label, "production") && !identical(update, "production")) {
    stopf("This is a production run; these changes would alter its results: %s. Use `update = \"production\"` to confirm, or a new run directory.",
          paste(altering, collapse = "; "))
  }
  if (length(changes)) {
    man$revisions <- c(man$revisions, list(list(time = now_utc(), changes = changes,
      types = ifelse(alters, "alter", "extend"),
      added_methods = setdiff(names(new$methods), names(old$methods)),
      fingerprint_before = man$study_fingerprint,
      fingerprint_after = study_fp)))
  }
  man$rng_registry <- rng_registry(rng_keys(study), man$rng_registry)
  attr(study, "adempr_stored") <- NULL
  man$study <- strip_sources(study)
  man$fingerprints <- new
  man$study_fingerprint <- study_fp
  man$replications <- max(man$replications, as.integer(replications))
  man
}

# Each call that works on a run directory records its computing environment.
# A session whose software differs from the one that created the directory
# is recorded and reported, because results may then differ numerically.
record_session <- function(man) {
  env <- environment_info(study_packages(man$study))
  man$sessions <- c(man$sessions, list(env))
  if (!identical(environment_signature(env), environment_signature(man$environment))) {
    warnf("The computing environment differs from the one that created this run directory (R, platform, BLAS or package versions). The new session is recorded in the manifest and shown in the report.")
  }
  g <- env$git
  if (identical(man$label, "production") && !is.null(g) && isTRUE(g$dirty)) {
    warnf("Production run from a git working tree with uncommitted changes (commit %s): the code that produced these results cannot be recovered from version control.",
          substr(g$commit, 1, 12))
  }
  man
}

# A frozen study may change only through sim_amend(), which records the new
# hash. A study read back from a manifest is not rechecked: its fingerprint
# recomputed in another session can differ for reasons unrelated to edits.
check_frozen <- function(study) {
  frozen <- study$status$frozen
  if (is.null(frozen) || isTRUE(attr(study, "adempr_stored"))) return(invisible())
  expected <- frozen$amended_hash %||% frozen$hash
  # a shard or calibration of a frozen study is checked through its parent
  der <- attr(study, "adempr_derived")
  if (!is.null(der)) {
    if (!identical(der$parent, expected)) {
      stopf("This study was changed after it was frozen without `sim_amend()`.")
    }
    return(invisible())
  }
  if (!identical(sim_fingerprint(study), expected)) {
    stopf("This study was changed after it was frozen without `sim_amend()`. Record the change with `sim_amend(study, ..., reason = )`, or freeze it again with `sim_freeze()` if no results were seen.")
  }
  invisible()
}

#' Run, extend or resume a simulation study
#'
#' Executes the study in a run directory. Each task generates one data set
#' and applies every method to it. Results are committed atomically in
#' batches, so an interrupted run loses at most the batches in progress and
#' can be resumed by calling `sim_run()` again (or [sim_resume()]) with the
#' same directory. Calling it with more replications or additional methods
#' extends the run: committed work is reused and every existing random
#' number assignment is preserved.
#'
#' The run directory refuses incompatible work: a different seed or data
#' generating mechanism is an error, and a changed method is refit only
#' with `update = TRUE`. Changes to truth, estimand metadata, measures or
#' the failure policy need no recomputation of fits and are applied by
#' [sim_summarise()]. Added scenarios and methods are run; removed ones keep
#' their committed results on disk but are excluded from summaries. A
#' changed `timeout` or number of `retries` applies to new work only;
#' committed fits keep the settings they ran with. Requesting fewer
#' replications than the directory holds gives a warning and keeps them all.
#' Each of these changes is recorded as a revision in the manifest.
#'
#' Every call records its computing environment as a session in the
#' manifest, and warns when the software differs from the session that
#' created the directory. When the working directory (or
#' `getOption("adempR.git_dir")`) is inside a git repository and the git
#' command line tool is installed, the commit, branch, remote URL (with
#' any embedded credentials removed) and whether the tree has uncommitted
#' changes are recorded too; a production run from a tree with uncommitted
#' changes gives a warning. Nothing is written to the repository.
#'
#' Backends: `"sequential"` is the reference implementation. `"future"`
#' distributes chunks of tasks with \pkg{future.apply} using the current
#' [future::plan()] (or a temporary multisession plan with `workers`
#' workers, restored on exit). Seeds are preassigned per task, so results
#' are identical across backends, worker counts and chunk sizes.
#' Parallel methods that use multithreaded linear algebra can oversubscribe
#' cores; limit threads (for example `OMP_NUM_THREADS`) when using many
#' workers.
#'
#' @param study A [sim_study()].
#' @param replications Number of replications per scenario.
#' @param seed Base seed of the run.
#' @param path Run directory. Created if needed.
#' @param backend `"sequential"` or `"future"`.
#' @param chunk_size Tasks per committed batch.
#' @param workers For `backend = "future"`, number of multisession workers;
#'   `NULL` uses the current plan.
#' @param max_tasks Refuse to schedule more than this many method fits
#'   (scenario x replication x method) in one call; a guard against
#'   unintentionally enormous designs. It is checked before the manifest
#'   is changed or any task is built.
#' @param update Allow refitting methods whose definition changed. In a
#'   run labeled `"production"`, any change that supersedes or re-evaluates
#'   committed results (a changed method, truth, estimand, measure, failure
#'   policy or design, or a removed method or scenario) is refused unless
#'   `update = "production"`; extensions are always allowed.
#' @param retry_failed Rerun replications whose data generation failed and
#'   method fits that ended in an error, a timeout or a memory failure,
#'   with their original
#'   random number streams. Use it after fixing a failure caused by the
#'   computing environment (a missing file, package or license, memory).
#'   The retry is recorded as a revision and its results supersede the
#'   earlier ones; without it, failures are final and are never rerun.
#' @param label Run label; defaults to the study status (`"draft"`,
#'   `"pilot"` or `"production"`).
#' @param progress Print progress messages.
#' @param rng_registry For a new run directory only: the stream registry of
#'   an earlier run (`res$manifest$rng_registry`), so that a regeneration
#'   uses the same stream of every scenario, method and truth even when the
#'   original run was extended with new methods or scenarios over time.
#'   Ignored when the directory already holds a run.
#' @param scenario_replications Optional replication counts for some
#'   scenarios above `replications`, named by scenario label or key (see
#'   [sim_run_adaptive()]). Counts only increase; they are stored in the
#'   manifest and used by every summary.
#' @param gpus Optional GPU device identifiers. Methods declared with
#'   `sim_method(gpu = TRUE)` see their batch's device (see [sim_method()]),
#'   and the device is recorded in the `gpu` column of their attempts.
#'   Sequential batches take the devices in turn. With the future backend,
#'   batches run in waves of one batch per worker, the k-th batch of a wave
#'   on the k-th device, so batches running at the same time use different
#'   devices when there are at least as many devices as workers (a warning
#'   says otherwise).
#' @param cost Optional function of the scenario returning the relative cost
#'   of one task (for example `function(scenario) scenario$n^2`, or times
#'   per scenario from [sim_pilot()]). Tasks are then scheduled longest
#'   first (LPT), which shortens the total time with parallel workers when
#'   scenarios differ in cost. Scheduling never changes results: every task
#'   has its own preassigned streams.
#' @return An object of class `adempr_run`.
#' @examples
#' study <- sim_study("demo", scenarios = sim_scenarios(n = c(10L, 40L)),
#'   generate = function(scenario, context) rnorm(scenario$n),
#'   estimands = list(sim_estimand("mean", sim_truth_exact(function(scenario) 0))),
#'   methods = list(avg = function(data) {
#'     sim_estimate("mean", mean(data), se = sd(data) / sqrt(length(data)))
#'   }))
#' path <- tempfile("adempR-run-")
#' run <- sim_run(study, replications = 20, seed = 1, path = path)
#' run <- sim_run(study, replications = 40, seed = 1, path = path) # extends
#' run
#' @export
sim_run <- function(study, replications, seed, path, backend = c("sequential", "future"),
                    chunk_size = 25L, workers = NULL, max_tasks = 1e6,
                    update = FALSE, retry_failed = FALSE, label = NULL,
                    progress = interactive(), rng_registry = NULL, cost = NULL,
                    scenario_replications = NULL, gpus = NULL) {
  stopifnot(inherits(study, "adempr_study"))
  backend <- match.arg(backend)
  if (!is.null(gpus) && (!length(gpus) || anyNA(gpus) || !(is.numeric(gpus) || is.character(gpus)))) {
    stopf("`gpus` must be device identifiers, for example 0:1.")
  }
  if (!(isTRUE(update) || isFALSE(update) || identical(update, "production"))) {
    stopf("`update` must be TRUE, FALSE or \"production\".")
  }
  if (!is_count(replications, 1)) stopf("`replications` must be a positive whole number.")
  if (!is_count(seed)) stopf("`seed` must be a nonnegative whole number.")
  if (missing(path) || !is_scalar_character(path)) {
    stopf("`path` must name a run directory, for example tempfile(\"adempR-run-\").")
  }
  if (!is_count(chunk_size, 1)) stopf("`chunk_size` must be a positive whole number.")
  sim_validate(study, error = TRUE)
  check_frozen(study)
  warn_patched(study_packages(study))
  replications <- as.integer(replications)
  p <- run_paths(path)
  if (dir.exists(path) && !file.exists(p$manifest)) {
    # an empty directory, or one left by a first call stopped before its
    # first manifest (only the run's own empty folders), may be used
    own <- c("LOCK", "batches", "truth", "tmp", "quarantine")
    if (length(setdiff(list.files(path, all.files = TRUE, no.. = TRUE), own)) ||
        length(list.files(p$batches))) {
      stopf("%s exists and is not an adempR run directory; refusing to write into it.", path)
    }
  }
  ensure_dirs(p)
  lock_token <- acquire_lock(p)
  on.exit(release_lock(p, lock_token), add = TRUE)
  existing <- file.exists(p$manifest)
  man <- if (existing) {
    reconcile_manifest(read_manifest(path), study, seed, replications, update)
  } else {
    new_manifest(study, seed, replications,
                 label %||% study$status$label, rng_registry)
  }
  if (!existing && !is.null(attr(study, "adempr_derived"))) {
    man$derived_from <- attr(study, "adempr_derived")
  }
  if (!existing && !is.null(attr(study, "adempr_sequential"))) {
    man$sequential <- list(design = attr(study, "adempr_sequential"))
  }
  revise <- function(man, text) {
    man$revisions <- c(man$revisions, list(list(time = now_utc(), changes = text,
      fingerprint_before = man$study_fingerprint, fingerprint_after = man$study_fingerprint)))
    man
  }
  if (existing && isTRUE(label %in% c("pilot", "calibration")) &&
      !identical(man$rng_domain, label)) {
    # pilot and calibration work draws from its own stream family, fixed
    # when a directory is created; an existing directory of another kind
    # would give it the production data
    stopf("%s holds a run on the %s random number streams; a %s run needs its own directory.",
          path, man$rng_domain %||% "production", label)
  }
  is_production <- identical(man$label, "production")
  if (existing && !is.null(label) && !identical(label, man$label)) {
    # The label of an existing run is part of its record; a production run
    # cannot be relabeled (and thereby unprotected) without confirmation.
    # The random number domain was fixed when the directory was created and
    # does not follow the label.
    if (is_production && !identical(update, "production")) {
      stopf("This is a production run; relabeling it \"%s\" would lift its protection. Use `update = \"production\"` to confirm, or a new run directory.",
            label)
    }
    man <- revise(man, sprintf("run label changed from %s to %s", man$label, label))
  }
  if (!is.null(label)) man$label <- label
  p$method_fps <- unlist(man$fingerprints$methods)
  p$generator_fp <- man$fingerprints$generator
  done <- committed_index(path, p$method_fps, p$generator_fp, retry = retry_failed)
  # the budget is checked before the manifest changes or the task grid exists
  if (!is.null(scenario_replications)) {
    sr <- scenario_replications
    if (!is.numeric(sr) || is.null(names(sr)) || any(!vapply(sr, is_count, logical(1), min = 1))) {
      stopf("`scenario_replications` must be positive whole numbers named by scenario.")
    }
    ks <- vapply(names(sr), function(s) resolve_scenario(study, s), character(1))
    cur <- man$scenario_replications %||% integer()
    for (i in seq_along(ks)) cur[[ks[i]]] <- max(cur[ks[i]] %||% 0L, as.integer(sr[[i]]), na.rm = TRUE)
    if (!identical(cur, man$scenario_replications)) {
      man <- revise(man, sprintf("replications raised for %d scenario(s): %s", length(ks),
        paste(sprintf("%s to %d", study$scenarios$labels[match(ks, study$scenarios$keys)],
                      as.integer(cur[ks])), collapse = ", ")))
    }
    man$scenario_replications <- cur
  }
  plan_R <- planned_replications(man, study$scenarios$keys)
  if (!is.null(man$sequential$analyzed)) plan_R[] <- man$replications
  n_todo <- count_tasks(study, plan_R, done)
  if (n_todo > 0 && isTRUE(attr(study, "adempr_stored"))) {
    # A stored study is reused without recomputing its fingerprints, which
    # is right for reading. New work runs its live closures, so they must
    # still be the code that produced the committed results.
    live <- tryCatch(study_fingerprints(study), error = function(e) NULL)
    stale <- c(if (!identical(live$generator, man$fingerprints$generator)) "the generator",
               names(Filter(isTRUE, Map(function(a, b) !identical(a, b),
                                        live$methods, man$fingerprints$methods[names(live$methods)]))))
    if (is.null(live) || length(stale)) {
      stopf("The stored study cannot run new work in this session: %s now depend%s on objects (global variables or packages) that differ from those of the committed results, so new fits would mix two implementations under one fingerprint. Restore those objects, or call sim_run() with the study object (and `update = TRUE` for changed methods).",
            if (is.null(live)) "its code" else paste(stale, collapse = ", "),
            if (length(stale) == 1L) "s" else "")
    }
  }
  if (n_todo > max_tasks) {
    stopf(class = "adempr_too_many_tasks", "This call would run %s method fits (%d scenarios x up to %d replications x %d methods), more than `max_tasks` = %s. Check the design or raise `max_tasks` deliberately.",
          format(n_todo, big.mark = ","), length(study$scenarios), max(plan_R),
          length(study$methods), format(max_tasks, big.mark = ","))
  }
  if (sum(attr(done, "retried")) && is_production && !identical(update, "production")) {
    stopf("This is a production run; a retry supersedes %d committed result(s). Use `update = \"production\"` with `retry_failed = TRUE` to confirm.",
          sum(attr(done, "retried")))
  }
  man <- record_session(man)
  man$status <- "running"
  write_manifest(p, man)

  retried <- attr(done, "retried")
  p$round <- man$retry_round %||% 0L
  if (sum(retried)) {
    p$round <- p$round + 1L
    man$retry_round <- p$round
    man$revisions <- c(man$revisions, list(list(time = now_utc(),
      changes = sprintf("retry round %d: rerun %d failed generation(s) and %d failed method fit(s) with their original random number streams",
                        p$round, retried[["generation"]], retried[["method"]]),
      fingerprint_before = man$study_fingerprint, fingerprint_after = man$study_fingerprint)))
    write_manifest(p, man)
  }
  todo <- plan_tasks(study, plan_R, done)
  ctx <- list(seed = seed, domain = man$rng_domain, registry = man$rng_registry,
              cache = new.env(parent = emptyenv()),
              dgp_stage = "dgp", method_stage = "method")
  if (nrow(todo)) {
    tasks <- build_tasks(study, ctx, todo, attr(done, "data_md5"))
    if (!is.null(cost)) tasks <- lpt_order(study, tasks, cost)
    chunks <- split(tasks, ceiling(seq_along(tasks) / chunk_size))
    if (progress) {
      message(sprintf("Running %d task(s) in %d batch(es) with the %s backend.",
                      length(tasks), length(chunks), backend))
    }
    run_chunks(study, chunks, p, backend, workers, progress, gpus)
  }
  man$status <- "complete"
  man$completed <- now_utc()
  write_manifest(p, man)
  run <- structure(list(path = normalizePath(path), manifest = man), class = "adempr_run")
  # evaluate and cache the truths now, under the run lock and with the
  # definitions that produced these results
  sim_truth(run)
  run
}

#' @rdname sim_run
#' @param ... Further arguments passed to `sim_run()`.
#' @export
sim_resume <- function(path, ...) {
  man <- read_manifest(path)
  args <- list(...)
  study <- args$study
  if (is.null(study)) {
    study <- man$study
    attr(study, "adempr_stored") <- TRUE
  }
  args$study <- NULL
  do.call(sim_run, c(list(study = study, replications = args$replications %||% man$replications,
                          seed = man$seed, path = path),
                     args[setdiff(names(args), "replications")]))
}

#' Open an existing run directory
#'
#' @param path Run directory.
#' @return An object of class `adempr_run`.
#' @examples
#' study <- sim_study("demo", scenarios = sim_scenarios(n = 10L),
#'   generate = function(scenario, context) rnorm(scenario$n),
#'   estimands = list(sim_estimand("mean", sim_truth_exact(function(scenario) 0))),
#'   methods = list(avg = function(data) sim_estimate("mean", mean(data))))
#' path <- tempfile("adempR-run-")
#' sim_run(study, replications = 5, seed = 1, path = path)
#' sim_open(path)
#' @export
sim_open <- function(path) {
  structure(list(path = normalizePath(path), manifest = read_manifest(path)),
            class = "adempr_run")
}

#' @export
print.adempr_run <- function(x, ...) {
  m <- x$manifest
  cat(sprintf("<adempR run of `%s` (%s, %s)>\n", m$study$name, m$label, m$status))
  cat(sprintf("Directory:    %s\n", x$path))
  cat(sprintf("Seed:         %s\n", m$seed))
  cat(sprintf("Replications: %d per scenario, %d scenario(s), %d method(s)\n",
              m$replications, length(m$study$scenarios), length(m$study$methods)))
  if (length(m$revisions)) cat(sprintf("Revisions:    %d\n", length(m$revisions)))
  invisible(x)
}

# Fit outcomes that `retry_failed = TRUE` reruns: failures that can come
# from the computing environment rather than from the method.
RETRYABLE_STATUSES <- c("error", "timeout", "memory")

# Which (scenario, replication, method) combinations are committed with the
# current method fingerprints.
# A replication whose generation failed counts as finished for every
# method: it is not rerun unless a retry is requested.
committed_index <- function(path, fps, gen_fp, retry = FALSE) {
  res <- read_raw_results(path, repair = TRUE)
  est <- res$estimates
  att <- res$attempts
  reps <- res$replications
  empty <- data.frame(scenario_key = character(), replication = integer(),
                      method = character(), stringsAsFactors = FALSE)
  done <- empty
  if (!is.null(est) && nrow(est)) {
    cur <- est$method %in% names(fps) & est$method_fp == fps[est$method]
    done <- unique(est[cur, c("scenario_key", "replication", "method")])
    if (retry && !is.null(att) && nrow(att)) {
      bad <- att[att$final & att$status %in% RETRYABLE_STATUSES &
                   att$method %in% names(fps) & att$method_fp == fps[att$method], , drop = FALSE]
      id_bad <- paste(bad$scenario_key, bad$replication, bad$method, sep = "\r")
      done <- done[!(paste(done$scenario_key, done$replication, done$method, sep = "\r") %in%
                       id_bad), , drop = FALSE]
    }
  }
  failed_gen <- 0L
  failed_fit <- 0L
  if (!is.null(reps) && nrow(reps)) {
    gf <- unique(reps[reps$generator_fp == gen_fp & reps$generation_status != "ok",
                      c("scenario_key", "replication")])
    failed_gen <- nrow(gf)
    if (nrow(gf) && !retry) {
      done <- unique(rbind(done, merge(gf, data.frame(method = names(fps),
                                                       stringsAsFactors = FALSE))))
    }
  }
  if (retry && !is.null(att) && nrow(att)) {
    failed_fit <- sum(att$final & att$status %in% RETRYABLE_STATUSES &
                        att$method %in% names(fps) & att$method_fp == fps[att$method])
  }
  attr(done, "retried") <- c(generation = if (retry) failed_gen else 0L,
                             method = failed_fit)
  # checksums of the committed data sets: work added to a replication later
  # (a retry, an added or changed method) must see the same data
  if (!is.null(reps) && nrow(reps) && "data_md5" %in% names(reps)) {
    ok <- reps[reps$generator_fp == gen_fp & reps$generation_status == "ok" &
                 !is.na(reps$data_md5), c("scenario_key", "replication", "data_md5")]
    attr(done, "data_md5") <- stats::setNames(ok$data_md5,
                                              paste(ok$scenario_key, ok$replication, sep = "\r"))
  }
  done
}

# Number of method fits still to run, without building the grid.
# `R` is one replication count, or one per scenario (named by key).
per_scenario <- function(R, keys) {
  if (length(R) == 1L && is.null(names(R))) return(stats::setNames(rep(as.integer(R), length(keys)), keys))
  stats::setNames(as.integer(R[keys]), keys)
}

count_tasks <- function(study, R, done) {
  keys <- study$scenarios$keys
  Rs <- per_scenario(R, keys)
  ms <- names(study$methods)
  d <- done[done$scenario_key %in% keys & done$method %in% ms &
              done$replication <= Rs[done$scenario_key], , drop = FALSE]
  n_done <- length(unique(paste(d$scenario_key, d$replication, d$method, sep = "\r")))
  sum(as.numeric(Rs)) * length(ms) - n_done
}

plan_tasks <- function(study, R, done) {
  keys <- study$scenarios$keys
  Rs <- per_scenario(R, keys)
  grid <- expand.grid(replication = seq_len(max(Rs)), scenario_key = keys,
                      method = names(study$methods), stringsAsFactors = FALSE)
  grid <- grid[grid$replication <= Rs[grid$scenario_key], , drop = FALSE]
  id_all <- paste(grid$scenario_key, grid$replication, grid$method, sep = "\r")
  id_done <- paste(done$scenario_key, done$replication, done$method, sep = "\r")
  grid[!(id_all %in% id_done), c("scenario_key", "replication", "method")]
}

build_tasks <- function(study, ctx, todo, data_md5 = NULL) {
  out <- list()
  for (key in unique(todo$scenario_key)) {
    sub <- todo[todo$scenario_key == key, , drop = FALSE]
    reps <- sort(unique(sub$replication))
    seeds <- task_seeds(ctx, key, reps, study, names(study$methods))
    for (j in seq_along(reps)) {
      ms <- sub$method[sub$replication == reps[j]]
      ms <- names(study$methods)[names(study$methods) %in% ms]
      out[[length(out) + 1L]] <- list(scenario_key = key, replication = reps[j],
                                      seeds = seeds[[j]], methods = ms,
                                      expect_md5 = unname(data_md5[paste(key, reps[j], sep = "\r")]))
    }
  }
  out
}

run_chunk <- function(study, chunk) {
  lapply(chunk, function(task) execute_task_seeded(study, task))
}

commit_chunk <- function(study, results, p) {
  fps <- p$method_fps
  gen_fp <- p$generator_fp
  arts <- list()
  reps <- lapply(results, function(r) {
    rep <- r$replication
    rep$generator_fp <- gen_fp
    rep$artifact <- NA_character_
    rep$artifact_fits <- NA_character_
    rep$artifact_data <- NA
    if (length(r$artifacts)) {
      dir <- file.path(p$root, "artifacts")
      if (!dir.exists(dir)) dir.create(dir)
      nm <- paste0("a-", short_hash(rep$scenario_key), "-r", rep$replication, "-",
                   new_uuid())
      atomic_save(r$artifacts, dir, nm, p$tmp)
      rep$artifact <- file.path("artifacts", paste0(nm, ".rds"))
      # each artifact lists the method versions whose fits it holds
      fm <- names(r$artifacts$fits)
      rep$artifact_fits <- if (length(fm)) paste0(fm, "=", fps[fm], collapse = ";") else ""
      rep$artifact_data <- !is.null(r$artifacts$data)
    }
    rep
  })
  est <- bind_rows(lapply(results, `[[`, "estimates"))
  if (!is.null(est)) est$method_fp <- unname(fps[est$method])
  att <- bind_rows(lapply(results, `[[`, "attempts"))
  if (!is.null(att)) att$method_fp <- unname(fps[att$method])
  rnd <- function(df) {
    if (!is.null(df) && nrow(df)) df$round <- as.integer(p$round)
    df
  }
  dg <- bind_rows(lapply(results, `[[`, "diagnostics"))
  if (!is.null(dg)) dg$method_fp <- unname(fps[dg$method])
  batch <- list(schema_version = SCHEMA_VERSION, created = now_utc(),
                replications = rnd(bind_rows(reps)), attempts = rnd(att), estimates = rnd(est),
                diagnostics = rnd(dg),
                records = rnd(bind_rows(lapply(results, `[[`, "records"))),
                dataset_truth = rnd(bind_rows(lapply(results, `[[`, "dataset_truth"))))
  nm <- paste0("b-", new_uuid())
  atomic_save(batch, p$batches, nm, p$tmp)
  # the inventory lists every committed batch, so a batch deleted together
  # with its sidecar is detected instead of silently shrinking the results
  cat(nm, "\n", sep = "", file = file.path(p$batches, "INVENTORY"), append = TRUE)
}

# Declared packages are attached only while the callback that declared them
# runs (the generator and its record, or one method's fit, extract,
# fallback and diagnostics), in every backend, so an unqualified call
# resolves the same way everywhere and one method's packages never mask
# the functions another method calls. Packages attached for the call are
# detached afterwards, so the caller's search path is the same before and
# after.
attach_packages <- function(pkgs) {
  for (pkg in pkgs) {
    suppressPackageStartupMessages(library(pkg, character.only = TRUE))
  }
  invisible(pkgs)
}

with_packages <- function(pkgs, code) {
  restore <- local_packages(pkgs)
  on.exit(restore(), add = TRUE)
  force(code)
}

# Attach `pkgs` and return a function that detaches what was attached.
local_packages <- function(pkgs) {
  before <- search()
  attach_packages(pkgs)
  function() {
    for (a in setdiff(search(), before)) {
      if (startsWith(a, "package:")) {
        try(detach(a, character.only = TRUE, unload = FALSE), silent = TRUE)
      }
    }
  }
}

# Functions defined at top level refer to helpers in the global environment,
# which a separate worker process does not have. Every study function whose
# environment is the global environment, and every global function it calls
# in turn, is given a private environment holding copies of the global
# objects it uses. Values and fingerprints are unchanged.
localize_globals <- function(study) {
  shared <- new.env(parent = globalenv())
  todo <- list()
  collect <- function(f) {
    if (!is.function(f) || is.primitive(f) || !identical(environment(f), globalenv())) return()
    vars <- tryCatch(codetools::findGlobals(f), error = function(e) character())
    for (v in setdiff(vars, ls(shared, all.names = TRUE))) {
      if (!exists(v, envir = globalenv(), inherits = FALSE)) next
      val <- get(v, envir = globalenv(), inherits = FALSE)
      assign(v, val, envir = shared)
      collect(val)
    }
  }
  rebind <- function(x) {
    if (is.function(x) && !is.primitive(x) && identical(environment(x), globalenv())) {
      environment(x) <- shared
      return(x)
    }
    if (is.list(x) && !is.data.frame(x) && length(x)) {
      a <- attributes(x)
      x <- lapply(x, rebind)
      attributes(x) <- a
    }
    x
  }
  walk <- function(x) {
    if (is.function(x)) collect(x)
    else if (is.list(x) && !is.data.frame(x)) for (el in x) walk(el)
  }
  walk(unclass(study))
  for (v in ls(shared, all.names = TRUE)) assign(v, rebind(get(v, envir = shared)), envir = shared)
  rebind(study)
}

# A function created inside another function keeps its own enclosing
# environment, which travels to the workers. Global objects it reaches only
# by falling through to the global environment do not travel, and copying
# them would mean changing the user's environments. Such references are
# found before the run and refused, instead of failing on every worker.
unshipped_globals <- function(study) {
  seen <- new.env(parent = emptyenv())
  out <- character()
  visit <- function(f) {
    if (!is.function(f) || is.primitive(f)) return()
    env <- environment(f)
    if (is.null(env) || identical(env, globalenv()) || isNamespace(env)) return()
    id <- paste(utils::capture.output(print(env)), collapse = "")
    key <- paste(id, paste(deparse(f), collapse = ""))
    if (exists(key, envir = seen, inherits = FALSE)) return()
    assign(key, TRUE, envir = seen)
    for (v in tryCatch(codetools::findGlobals(f), error = function(e) character())) {
      e <- env
      repeat {
        if (identical(e, emptyenv()) || isNamespace(e) || identical(e, baseenv())) break
        if (identical(e, globalenv())) {
          if (exists(v, envir = e, inherits = FALSE)) out <<- c(out, v)
          break
        }
        if (exists(v, envir = e, inherits = FALSE)) {
          visit(get(v, envir = e, inherits = FALSE))
          break
        }
        e <- parent.env(e)
      }
    }
  }
  walk <- function(x) {
    if (is.function(x)) visit(x)
    else if (is.list(x) && !is.data.frame(x)) for (el in x) walk(el)
  }
  walk(unclass(study))
  unique(out)
}

# The worker function lives in a minimal environment so that a future
# carries only its own chunk and the study, not the coordinator's frame.
chunk_worker <- local(function(chunk, study, packages) {
  run_chunk(study, chunk)
}, envir = new.env(parent = asNamespace("adempR")))

# Devices are assigned where batches are dispatched. Sequential batches
# take the devices in turn. With the future backend and devices, each wave
# holds one batch per worker, dispatched as one future each, and the k-th
# batch of a wave gets the k-th device, so batches that run at the same time
# never share a device.
# ponytail: a wave waits for its slowest batch; pin devices per persistent
# worker if that idle time matters.
with_device <- function(chunk, dev) {
  if (is.null(dev)) return(chunk)
  lapply(chunk, function(t) { t$gpu <- as.character(dev); t })
}

run_chunks <- function(study, chunks, p, backend, workers, progress, gpus = NULL) {
  dev_of <- function(k) if (is.null(gpus)) NULL else gpus[(k - 1L) %% length(gpus) + 1L]
  if (backend == "sequential") {
    for (i in seq_along(chunks)) {
      chunks[[i]] <- with_device(chunks[[i]], dev_of(i))
      commit_chunk(study, run_chunk(study, chunks[[i]]), p)
      if (progress) message(sprintf("  batch %d/%d committed", i, length(chunks)))
    }
    return(invisible(NULL))
  }
  for (pkg in c("future", "future.apply")) {
    if (!has_namespace(pkg)) {
      stopf("The future backend needs the %s package.", pkg)
    }
  }
  if (!is.null(workers)) {
    if (!is_count(workers, 1)) stopf("`workers` must be a positive whole number.")
    oplan <- future::plan(future::multisession, workers = workers)
    on.exit(future::plan(oplan), add = TRUE)
  }
  nw <- future::nbrOfWorkers()
  nw <- max(1L, as.integer(if (is.finite(nw)) nw else 1L))
  wave <- if (is.null(gpus)) nw * 2L else nw
  if (!is.null(gpus) && nw > length(gpus)) {
    warning(sprintf("%d workers share %d GPU device(s); some batches that run at the same time use the same device.",
                    nw, length(gpus)), call. = FALSE)
  }
  pkgs <- study_packages(study)
  missing <- unshipped_globals(study)
  if (length(missing)) {
    stopf("Study functions created inside other functions use global object(s) %s, which the future backend cannot send to workers. Define those functions at top level, pass the objects into the function that creates them, or use the sequential backend.",
          paste(missing, collapse = ", "))
  }
  shipped <- localize_globals(study)
  starts <- seq(1L, length(chunks), by = wave)
  for (s in starts) {
    idx <- s:min(s + wave - 1L, length(chunks))
    batch <- lapply(seq_along(idx), function(k) with_device(chunks[[idx[k]]], dev_of(k)))
    res <- future.apply::future_lapply(batch, chunk_worker, study = shipped,
                                       packages = pkgs, future.seed = FALSE,
                                       future.packages = "adempR", future.globals = FALSE,
                                       future.chunk.size = if (is.null(gpus)) NULL else 1L)
    for (r in res) commit_chunk(study, r, p)
    if (progress) message(sprintf("  batches %d to %d of %d committed", min(idx), max(idx),
                                  length(chunks)))
  }
  invisible(NULL)
}

# Streams of the truth stage: one per scenario and estimand, or one per
# distinct value of the declared factors of a shared Monte Carlo truth.
truth_stream_keys <- function(study) {
  keys <- study$scenarios$keys
  rows <- list()
  for (en in names(study$estimands)) {
    tr <- study$estimands[[en]]$truth
    tk <- vapply(seq_along(keys), function(i) {
      truth_key(tr, study$scenarios$values[[i]], keys[i])
    }, character(1))
    rows[[length(rows) + 1L]] <- data.frame(stage = "truth", scenario_key = unique(tk),
                                            component = en, stringsAsFactors = FALSE)
  }
  bind_rows(rows)
}

# A package is identified by name and version in fingerprints. A namespace
# loaded from source (pkgload::load_all()) or with traced or replaced
# functions runs code that its version number does not identify.
patched_namespaces <- function(pkgs) {
  pkgs <- pkgs[vapply(pkgs, isNamespaceLoaded, logical(1))]
  pkgs[vapply(pkgs, function(p) {
    ns <- asNamespace(p)
    if (exists(".__DEVTOOLS__", envir = ns, inherits = FALSE)) return(TRUE)
    any(vapply(ls(ns, all.names = TRUE), function(nm) {
      inherits(get(nm, envir = ns, inherits = FALSE), "functionWithTrace")
    }, logical(1)))
  }, logical(1))]
}

warn_patched <- function(pkgs) {
  bad <- patched_namespaces(pkgs)
  if (length(bad)) {
    warning(sprintf(paste0("Package(s) %s are loaded from source or have traced functions; ",
                           "fingerprints identify packages by name and version, which do not ",
                           "identify this code. Install the package and restart R before a ",
                           "production run."), paste(bad, collapse = ", ")), call. = FALSE)
  }
  invisible(bad)
}

# Longest processing time first: tasks of costly scenarios start first, so
# workers finish close together instead of waiting on a late costly chunk.
lpt_order <- function(study, tasks, cost) {
  check_function(cost, "cost", "scenario")
  keys <- unique(vapply(tasks, `[[`, character(1), "scenario_key"))
  w <- vapply(keys, function(k) {
    v <- call_flexible(cost, list(scenario = study$scenarios$values[[scenario_index(study$scenarios, k)]]))
    if (!is_scalar_number(v) || v < 0) stopf("`cost` must return one nonnegative number per scenario.")
    as.numeric(v)
  }, numeric(1))
  tk <- vapply(tasks, `[[`, character(1), "scenario_key")
  tasks[order(-w[tk], seq_along(tasks))]
}

# Replications planned per scenario: the run's count, raised for scenarios
# that received more by adaptive allocation.
planned_replications <- function(man, keys) {
  R <- stats::setNames(rep(as.integer(man$replications), length(keys)), keys)
  extra <- man$scenario_replications
  if (length(extra)) {
    k <- intersect(names(extra), keys)
    R[k] <- pmax(R[k], as.integer(extra[k]))
  }
  if (!is.null(man$sequential$analyzed)) R <- pmin(R, man$sequential$analyzed)
  R
}
